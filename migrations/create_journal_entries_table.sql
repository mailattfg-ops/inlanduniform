-- 1. Create journal_entries table
CREATE TABLE IF NOT EXISTS public.journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT REFERENCES public.organizations(id) ON DELETE CASCADE,
    journal_no TEXT UNIQUE NOT NULL,
    reference_no TEXT,
    title TEXT NOT NULL,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    notes TEXT,
    currency TEXT DEFAULT 'INR - Indian Rupee',
    total_debit NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    total_credit NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    status TEXT DEFAULT 'Posted',
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Create journal_entry_lines table
CREATE TABLE IF NOT EXISTS public.journal_entry_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id BIGINT REFERENCES public.journal_entries(id) ON DELETE CASCADE,
    account TEXT NOT NULL,
    description TEXT,
    contact TEXT,
    debit NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    credit NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

